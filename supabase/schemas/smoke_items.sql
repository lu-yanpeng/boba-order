-- 冒烟试验田：`smoke_items`
-- 数据访问纪律示范（AD-16）：显式 GRANT ＋ 开 RLS。
-- 授权 anon/authenticated 读取，供 PostgREST 直读断言。真实域表落地时退役。

create table if not exists public.smoke_items (
  id bigint generated by default as identity primary key,
  label text not null
);

alter table public.smoke_items enable row level security;

create policy smoke_items_select on public.smoke_items
  for select
  to anon, authenticated
  using (true);

grant select on public.smoke_items to anon, authenticated;
